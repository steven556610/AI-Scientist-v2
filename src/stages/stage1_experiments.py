"""
src/stages/stage1_experiments.py
=================================
Stage 1 — Experiment execution via BFTS agent.

Public API
----------
run_experiment_stage(idea_config_path, idea_dir, stage_log_dir) -> bool
"""

import os
import os.path as osp
import shutil
import traceback

from src.io_utils import redirect_stdout_stderr_to_file
from src.logger import create_log_filename, get_default_log_dir

try:
    from ai_scientist.treesearch.perform_experiments_bfts_with_agentmanager import (
        perform_experiments_bfts,
    )
except ImportError:
    perform_experiments_bfts = None


def run_experiment_stage(
    idea_config_path: str,
    idea_dir: str,
    stage_log_dir: str,
) -> bool:
    """
    Run the BFTS experiment agent and copy results to *idea_dir*.

    Parameters
    ----------
    idea_config_path : str
        Path to the per-idea bfts_config.yaml generated by
        ``edit_bfts_config_file``.
    idea_dir : str
        Root output directory for this experiment run.
    stage_log_dir : str
        Directory where stage log files are written.

    Returns
    -------
    bool
        ``True`` if ``experiment_results/`` is non-empty after the run,
        ``False`` otherwise (triggers early-exit in the main launcher).
    """
    log_path = osp.join(stage_log_dir, "01_experiment_execution.log")
    central_log_path = osp.join(get_default_log_dir(), create_log_filename("stage1_experiments.py"))
    print(f"[Stage 1] Log → {log_path}")
    print(f"[Stage 1] Central Log → {central_log_path}")

    try:
        with redirect_stdout_stderr_to_file(log_path, central_log_path):
            perform_experiments_bfts(idea_config_path)
    except Exception:
        with open(log_path, "a") as fh:
            fh.write("\n\n=== EXCEPTION IN STAGE 1 ===\n")
            traceback.print_exc(file=fh)
        with open(central_log_path, "a") as fh:
            fh.write("\n\n=== EXCEPTION IN STAGE 1 ===\n")
            traceback.print_exc(file=fh)
        print(f"[Stage 1] ERROR: exception raised — see {log_path}")
        return False

    # Copy experiment_results out of the BFTS log tree for easier access.
    bfts_results = osp.join(idea_dir, "logs", "0-run", "experiment_results")
    dest = osp.join(idea_dir, "experiment_results")
    if osp.exists(bfts_results) and os.listdir(bfts_results):
        shutil.copytree(bfts_results, dest, dirs_exist_ok=True)
        print("[Stage 1] Completed successfully.")
        return True

    print(
        "[Stage 1] WARNING: experiment_results is empty or missing — "
        "downstream stages will be skipped."
    )
    return False
